from playwright.sync_api import sync_playwright
from PIL import Image
import io,sys,time
url='http://127.0.0.1:8767/'
with sync_playwright() as p:
 browser=p.chromium.launch(headless=True,executable_path='/usr/bin/chromium', args=['--no-sandbox','--disable-dev-shm-usage','--disable-gpu','--no-first-run'])
 page=browser.new_page(viewport={'width':1320,'height':920},device_scale_factor=1)
 errors=[]
 page.on('pageerror', lambda e: errors.append(str(e)))
 print('Opening coordination')
 page.goto(url+'coordination.html',wait_until='networkidle',timeout=30000)
 print('title',page.title(), 'H1',page.locator('h1').first.inner_text(timeout=5000))
 page.screenshot(path='/mnt/data/PEC_V0_3_0_COORDINATION_APERCU_PC.png',full_page=True)
 page.locator('[data-view="preparer"]').first.click()
 page.fill('#prep-first','ATT-DEMO-123')
 page.locator('#prep-review').check()
 page.locator('#prep-form button[type="submit"]').click()
 page.locator('[data-view="suivi"]').first.click()
 print('begin button',page.locator('[data-action="phase-pose"]').count(),page.locator('[data-action="phase-pose"]').get_attribute('disabled'))
 page.locator('[data-action="phase-pose"]').click()
 page.locator('#phase-form button[type="submit"]').click()
 page.locator('#actor').select_option('agent1')
 page.locator('[data-view="agents"]').first.click()
 print('declaration buttons', page.locator('[data-action="declare"]').count())
 page.locator('[data-action="declare"]').first.click()
 buf=io.BytesIO();Image.new('RGB',(120,120),'white').save(buf,format='PNG')
 page.locator('input[name="check0"]').check()
 for i in range(1,6):page.locator(f'input[name="check{i}"]').check()
 page.locator('#declaration-form input[name="confirm"]').check()
 page.set_input_files('#evidence-file', {'name':'demo_test_photo.png','mimeType':'image/png','buffer':buf.getvalue()})
 page.locator('#submit-declaration').click()
 page.wait_for_timeout(400)
 print('declaration modal count',page.locator('.dialog').count())
 page.locator('#actor').select_option('chef')
 print('review buttons',page.locator('[data-action="review"]').count())
 page.locator('[data-action="review"]').first.click()
 page.locator('#review-form input[name="confirm"]').check()
 page.locator('#review-form button[type="submit"]').click()
 page.wait_for_timeout(300)
 print('accepted statuses',page.locator('.pill.accepted').count())
 page.locator('[data-view="plan"]').first.click()
 page.screenshot(path='/mnt/data/PEC_V0_3_0_PLAN_APERCU_PC.png',full_page=True)
 print('Opening concepteur')
 page.goto(url+'concepteur.html',wait_until='networkidle')
 page.locator('#enhance-open').click()
 page.wait_for_timeout(200)
 print('enhance dialog open',page.locator('#enhance-dialog').evaluate('(el)=>el.open'))
 page.locator('#enhance-compare').click()
 page.locator('#enhance-close').click()
 print('errors',errors)
 page2=browser.new_page(viewport={'width':390,'height':844},device_scale_factor=1)
 page2.on('pageerror', lambda e: errors.append(str(e)))
 page2.goto(url+'coordination.html',wait_until='networkidle')
 page2.screenshot(path='/mnt/data/PEC_V0_3_0_COORDINATION_APERCU_MOBILE.png',full_page=True)
 print('mobile h1', page2.locator('h1').first.inner_text())
 print('errors final',errors)
 browser.close()
 if errors: sys.exit(2)
