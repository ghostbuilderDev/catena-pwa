assert.equal(C.canDepose(a,'pose','agent1'),false);
assert.equal(C.canDepose(a,'depose','agent1'),true);
assert.equal(C.canDepose(a,'depose','agent2'),false);
assert.equal(C.canClose([a],'depose'),false);
assert.equal(C.canClose([p({depose:{declared:true,verified:true}})],'depose'),true);
assert.equal(C.canClose([p({depose:{declared:true,verified:true,issue:true}})],'depose'),false);
const n=C.counts([a,b]);assert.equal(n.total,2);assert.equal(n.poseVerified,1);
