const assert=require('node:assert/strict');
const C=require('../site/core.js');
const p=(over={})=>({agent:'agent1',pose:null,depose:null,...over});
const proof={precheck:true,vat:true,postcheck:true,fixing:true,location:true};
assert.equal(C.validateEvidence('pose',proof,true,true),true);
assert.equal(C.validateEvidence('pose',{...proof,postcheck:false},true,true),false);
assert.equal(C.validateEvidence('pose',proof,false,true),false);
assert.equal(C.validateEvidence('depose',{removed:true,siteClear:true},true,true),true);
assert.equal(C.validateEvidence('depose',{removed:true,siteClear:false},true,true),false);
assert.equal(C.canPose(p(),'preparation','agent1'),false);
assert.equal(C.canPose(p(),'pose','agent2'),false);
assert.equal(C.canPose(p(),'pose','agent1'),true);
