assert.equal(C.canReviewPose(p({pose:{declared:true,actor:'agent1'}}),'pose','chef'),true);
assert.equal(C.canReviewPose(p({pose:{declared:true,issue:true,actor:'agent1'}}),'pose','chef'),false);
assert.equal(C.canReviewDepose(p({depose:{declared:true,issue:true,actor:'agent1'}}),'depose','chef'),false);
const a=p({pose:{declared:true,verified:true,actor:'agent1',reviewer:'chef'}});
const b=p({pose:{declared:true,verified:false,actor:'agent2'}});
assert.equal(C.canOpenDepose([a,b],'pose'),false);
assert.equal(C.canOpenDepose([a],'pose'),true);
