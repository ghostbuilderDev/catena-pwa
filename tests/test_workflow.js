const assert=require('node:assert/strict');
const W=require('../site/workflow.js');
const item=(id,number,wave,agent)=>({id,number,wave,agent,type:'rail',pose:{status:'pending'},retrait:{status:'pending'}});
const a=item('a','1',1,'agent1'),b=item('b','2',1,'agent2'),c=item('c','3',2,'agent1'),cv=item('cv','4',3,'agent3');
const s={phase:'preparation',items:[a,b,c,cv],firstStageRef:'',planReviewed:false,workEndRef:'',cessationRef:''};
assert.equal(W.canBeginPose(s),false,'Cannot start without documentary reference and plan review');
s.firstStageRef='ATT-N-001';s.planReviewed=true;
assert.equal(W.canBeginPose(s),true);
s.phase='pose';
assert.equal(W.canDeclare(s,a,'agent1','pose'),true);
assert.equal(W.canDeclare(s,b,'agent2','pose'),true,'Same group can proceed in parallel');
assert.equal(W.canDeclare(s,c,'agent1','pose'),false,'Next group must be blocked');
assert.equal(W.canDeclare(s,cv,'agent3','pose'),false,'CV next group blocked');
assert.equal(W.canDeclare(s,a,'agent2','pose'),false,'Only assigned agent');
a.pose={status:'declared',actor:'agent1'};
assert.equal(W.canReview(s,a,'agent1','pose'),false,'No self review');
assert.equal(W.canReview(s,a,'chef','pose'),true);
a.pose.status='accepted';
assert.equal(W.canDeclare(s,c,'agent1','pose'),false,'Other same wave item must be accepted');
b.pose={status:'issue',actor:'agent2'};
assert.equal(W.canReopen(s,b,'agent2','pose'),false);
assert.equal(W.canReopen(s,b,'chef','pose'),true);
assert.equal(W.canBeginTravail(s),false,'Issue blocks progression');
b.pose={status:'accepted',actor:'agent2'};
assert.equal(W.canDeclare(s,c,'agent1','pose'),true);
assert.equal(W.canDeclare(s,cv,'agent3','pose'),false);
c.pose={status:'accepted',actor:'agent1'};
assert.equal(W.canDeclare(s,cv,'agent3','pose'),true);
cv.pose={status:'accepted',actor:'agent3'};
assert.equal(W.canBeginTravail(s),true);
s.phase='travail';assert.equal(W.canBeginRetrait(s),false);
s.workEndRef='EXT-END-001';assert.equal(W.canBeginRetrait(s),true);
s.phase='retrait';
assert.equal(W.canDeclare(s,cv,'agent3','retrait'),true,'Reverse order: last wave first');
assert.equal(W.canDeclare(s,c,'agent1','retrait'),false,'Reverse order: intermediate wave blocked');
cv.retrait={status:'accepted',actor:'agent3'};
assert.equal(W.canDeclare(s,c,'agent1','retrait'),true);
assert.equal(W.canDeclare(s,a,'agent1','retrait'),false,'First wave removed last');
c.retrait={status:'accepted',actor:'agent1'};
assert.equal(W.canDeclare(s,a,'agent1','retrait'),true);
assert.equal(W.canDeclare(s,b,'agent2','retrait'),true);
a.retrait={status:'accepted',actor:'agent1'};
b.retrait={status:'accepted',actor:'agent2'};
assert.equal(W.canClose(s),false,'External cessation reference required');
s.cessationRef='CESS-001';assert.equal(W.canClose(s),true);
const bad={...s,phase:'preparation',items:[a,{...b,number:'1'}]};assert.ok(W.configurationErrors(bad).some(x=>x.includes('double')));
assert.ok(W.safePlan([{id:'p1',number:'1'}]));
assert.equal(W.safePlan([{id:'p1',number:''}]),false);
console.log('✓ PEC : ordre de pose/retrait, parallélisme, contrôle distinct, écarts et garde-fous documentaires.');
